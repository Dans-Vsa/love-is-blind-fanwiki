// Builds src/styles/fonts.css: a trimmed @font-face set.
// - Latin subsets of every font come from Fontsource.
// - Japanese text in the display font (Dela Gothic One) is served from ONE small
//   custom subset (src/assets/fonts/dela-gothic-one-jp.woff2) holding only the
//   CJK/kana glyphs that actually appear in src/, instead of ~40 Fontsource chunks.
//
// Re-run after adding Japanese text:  npm run fonts
// Regenerating the subset needs Python fontTools + the full TTF (OFL, google/fonts):
//   FONTTOOLS_PYTHON=/path/to/python DELA_TTF=/path/DelaGothicOne-Regular.ttf npm run fonts
// Without those env vars the committed subset is kept and only the CSS is rewritten.
import { readFile, readdir, writeFile, mkdir } from 'node:fs/promises';
import { execFileSync } from 'node:child_process';
import { join } from 'node:path';

const LATIN = [
  '@fontsource/dela-gothic-one/400.css',
  '@fontsource-variable/source-serif-4/wght.css',
  '@fontsource-variable/source-serif-4/wght-italic.css',
  '@fontsource/ibm-plex-mono/400.css',
  '@fontsource/ibm-plex-mono/600.css',
];
const KEEP_SUBSETS = /-(latin|latin-ext)-(?:wght|\d{3})-(?:normal|italic)/;
const SUBSET_FILE = 'src/assets/fonts/dela-gothic-one-jp.woff2';

async function walk(dir) {
  const out = [];
  for (const e of await readdir(dir, { withFileTypes: true })) {
    const p = join(dir, e.name);
    if (e.isDirectory()) out.push(...(await walk(p)));
    else if (/\.(astro|mdx?|ts|json)$/.test(e.name)) out.push(p);
  }
  return out;
}

// 1. Collect CJK / kana / full-width code points used anywhere in src/.
const used = new Set();
for (const file of await walk('src')) {
  for (const ch of await readFile(file, 'utf8')) {
    const cp = ch.codePointAt(0);
    if (cp >= 0x3000) used.add(cp);
  }
}
const cps = [...used].sort((a, b) => a - b);

// Compress into unicode-range syntax: U+3042,U+3044-3046,…
const ranges = [];
for (let i = 0; i < cps.length; i++) {
  let j = i;
  while (j + 1 < cps.length && cps[j + 1] === cps[j] + 1) j++;
  const hex = (n) => n.toString(16).toUpperCase();
  ranges.push(i === j ? `U+${hex(cps[i])}` : `U+${hex(cps[i])}-${hex(cps[j])}`);
  i = j;
}

// 2. Optionally regenerate the subset font.
const { FONTTOOLS_PYTHON: py, DELA_TTF: ttf } = process.env;
if (py && ttf) {
  await mkdir('src/assets/fonts', { recursive: true });
  execFileSync(py, [
    '-m', 'fontTools.subset', ttf,
    `--unicodes=${cps.map((c) => c.toString(16)).join(',')}`,
    '--flavor=woff2', '--layout-features=*', '--no-hinting', '--desubroutinize',
    `--output-file=${SUBSET_FILE}`,
  ], { stdio: 'inherit' });
  console.log(`subset: ${cps.length} glyphs -> ${SUBSET_FILE}`);
}

// 3. Write the stylesheet.
let out = '/* Generated by scripts/build-fonts.mjs. Do not edit by hand. */\n';
let kept = 0;
for (const css of LATIN) {
  const pkgDir = css.split('/').slice(0, 2).join('/');
  const text = await readFile(join('node_modules', css), 'utf8');
  for (const block of text.split(/(?=\/\* )/)) {
    if (!/@font-face/.test(block) || !KEEP_SUBSETS.test(block)) continue;
    kept++;
    out += block
      .replace(/,\s*url\([^)]*\.woff\) format\('woff'\)/, '')
      .replace(/url\(\.\/files\//g, `url(../../node_modules/${pkgDir}/files/`);
  }
}
out += `
/* dela-gothic-one-jp-400-normal (custom subset: ${cps.length} glyphs used on this site) */
@font-face {
  font-family: 'Dela Gothic One';
  font-style: normal;
  font-display: swap;
  font-weight: 400;
  src: url(../assets/fonts/dela-gothic-one-jp.woff2) format('woff2');
  unicode-range: ${ranges.join(',')};
}
`;
await writeFile('src/styles/fonts.css', out);
console.log(`fonts.css: ${kept} Latin blocks + 1 Japanese subset block (${cps.length} glyphs)`);
