// Builds src/styles/fonts.css: a trimmed @font-face set.
// Keeps Latin subsets, plus only those Japanese subsets of Dela Gothic One whose
// unicode-range covers a CJK/kana character that actually appears in src/.
// Re-run after adding new Japanese text: npm run fonts
import { readFile, readdir, writeFile } from 'node:fs/promises';
import { join } from 'node:path';

const SOURCES = [
  { css: '@fontsource/dela-gothic-one/400.css', cjk: true },
  { css: '@fontsource-variable/source-serif-4/wght.css' },
  { css: '@fontsource-variable/source-serif-4/wght-italic.css' },
  { css: '@fontsource/ibm-plex-mono/400.css' },
  { css: '@fontsource/ibm-plex-mono/600.css' },
];
const KEEP_SUBSETS = /-(latin|latin-ext)-(?:wght|\d{3})-(?:normal|italic)/;

async function walk(dir) {
  const out = [];
  for (const e of await readdir(dir, { withFileTypes: true })) {
    const p = join(dir, e.name);
    if (e.isDirectory()) out.push(...(await walk(p)));
    else if (/\.(astro|mdx?|ts|json)$/.test(e.name)) out.push(p);
  }
  return out;
}

const used = new Set();
for (const file of await walk('src')) {
  for (const ch of await readFile(file, 'utf8')) {
    const cp = ch.codePointAt(0);
    if (cp >= 0x3000) used.add(cp);
  }
}

const inRange = (range) =>
  range.split(',').some((part) => {
    const [a, b] = part.trim().replace('U+', '').split('-');
    const lo = parseInt(a, 16);
    const hi = b ? parseInt(b, 16) : lo;
    for (const cp of used) if (cp >= lo && cp <= hi) return true;
    return false;
  });

let out = '/* Generated by scripts/build-fonts.mjs. Do not edit by hand. */\n';
let kept = 0;
for (const { css, cjk } of SOURCES) {
  const pkgDir = css.split('/').slice(0, 2).join('/');
  const text = await readFile(join('node_modules', css), 'utf8');
  for (const block of text.split(/(?=\/\* )/)) {
    const range = block.match(/unicode-range:\s*([^;]+);/)?.[1];
    if (!range) continue;
    const latin = KEEP_SUBSETS.test(block);
    if (!latin && !(cjk && inRange(range))) continue;
    kept++;
    out += block
      // woff2 only (every target browser supports it)
      .replace(/,\s*url\([^)]*\.woff\) format\('woff'\)/, '')
      .replace(/url\(\.\/files\//g, `url(../../node_modules/${pkgDir}/files/`);
  }
}
await writeFile('src/styles/fonts.css', out);
console.log(`fonts.css: kept ${kept} @font-face blocks for ${used.size} CJK/kana glyphs`);
